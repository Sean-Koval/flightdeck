"""The suite's editorial rule, ported from agent-factory's tests/test_editorial.py.

agent-factory's AGENTS.md, "Writing for the site": a page answers one question for one reader;
a paragraph is at most 60 words, a sentence at most 25 (a semicolon ends one) and a page at most
700 words of prose, or it is split. Prose is measured on README.md and the Markdown in docs/, with
front matter, code blocks, HTML tags, headings and link targets removed. A wrapped line continues
its paragraph; a list item and a table cell are paragraphs of their own.

Older pages break the rule, so the check is a ratchet. editorial_baseline.json records each page's
debt; a page may not get longer than its recorded length (or 700 words), and may not gain a long
paragraph or sentence. A page not in the baseline, a new one included, meets the rule in full.
When a page improves, the baseline must follow: run `python tests/test_editorial.py --update`.
`python tests/test_editorial.py` prints the report.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
BASELINE = Path(__file__).with_name("editorial_baseline.json")
PARAGRAPH, SENTENCE, PAGE = 60, 25, 700

# Pages that may stay over 700 words, each with its reason; a prefix ending in "/" covers a
# directory. Their long paragraphs and sentences are still ratcheted. Add here only when
# splitting would hurt the reader.
LONG_PAGES: dict[str, str] = {
    "docs/cli.md": "generated from the Typer app by scripts/docs_reference.py; a reader looks one command up",
}
SKIP_DIRS: tuple[str, ...] = ("assets",)  # docs/assets/ is generated by docs/assets/build.py

# Writing that is not prose: a heading, a snippet include, a tag on its own line, an image, a line
# of buttons, an admonition title, a link reference definition, an abbreviation.
SKIP_LINE = re.compile(
    r"^\s*(#|--8<--|<[a-zA-Z/!]|!\[|\[[^\]]*\]\([^)]*\)\s*$|:|!!!|\?\?\?|\*\[|\[[^\]]+\]:\s)"
)
TABLE_RULE = re.compile(r"^\s*\|?\s*:?-{3,}")
ITEM = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+")
FENCE = re.compile(r"^([ \t]*)(`{3,}|~{3,}).*?^\1\2[ \t]*$", re.DOTALL | re.MULTILINE)


def pages() -> list[Path]:
    out = [ROOT / "README.md"]
    for p in sorted(DOCS.rglob("*.md")):
        if any(part in SKIP_DIRS for part in p.relative_to(DOCS).parts[:-1]):
            continue
        out.append(p)
    return out


def rel(page: Path) -> str:
    return page.relative_to(ROOT).as_posix()


def plain(md: str) -> str:
    md = re.sub(r"<[^>]+>", "", md)
    md = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", md)
    md = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", md)  # link text only
    md = re.sub(r"\[([^\]]*)\]\[[^\]]*\]", r"\1", md)
    md = re.sub(r"`[^`]*`", "code", md)  # a code span is one word
    md = re.sub(r"[*_]{1,2}", "", md)
    md = re.sub(r"\{\s*[.#:][^}]*\}", "", md)  # attr_list
    md = md.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">").replace("\\|", "|")
    md = re.sub(r"^\s*>\s?", "", md)
    return " ".join(md.split())


def prose(text: str) -> list[str]:
    """Return a page's paragraphs as plain prose."""
    text = re.sub(r"\A---\n.*?\n---\n", "", text, flags=re.DOTALL)  # front matter
    text = FENCE.sub("", text)  # code blocks, indented ones in list items too
    text = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    text = re.sub(r"<(style|script|svg|figure)\b.*?</\1>", "", text, flags=re.DOTALL)
    paragraphs: list[str] = []
    current: list[str] = []

    def flush() -> None:
        if current:
            para = plain(" ".join(current))
            if para:
                paragraphs.append(para)
            current.clear()

    for line in text.splitlines():
        if not line.strip() or SKIP_LINE.match(line) or TABLE_RULE.match(line):
            flush()
            continue
        if line.lstrip().startswith("|"):  # a table: every cell is read on its own
            flush()
            cells = (plain(c) for c in line.strip().strip("|").split("|"))
            paragraphs.extend(c for c in cells if c)
            continue
        if ITEM.match(line):
            flush()
            line = ITEM.sub("", line)
        current.append(line.strip())
    flush()
    return paragraphs


def sentences(paragraph: str) -> list[str]:
    # split on . ! ? followed by space and a letter, a quote or a parenthesis; a semicolon ends an
    # independent clause, so it counts as a sentence end too. Version numbers do not split.
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Za-z\"'(])|;\s+", paragraph)
    return [p for p in parts if p.strip()]


def words(s: str) -> int:
    return len(s.split())


def measure(page: Path) -> dict[str, int]:
    paras = prose(page.read_text(encoding="utf-8"))
    return {
        "words": sum(words(p) for p in paras),
        "long_paragraphs": sum(1 for p in paras if words(p) > PARAGRAPH),
        "long_sentences": sum(1 for p in paras for s in sentences(p) if words(s) > SENTENCE),
    }


def long_page_reason(name: str) -> str | None:
    for key, reason in LONG_PAGES.items():
        if name == key or (key.endswith("/") and name.startswith(key)):
            return reason
    return None


def debt(name: str, m: dict[str, int]) -> dict[str, int]:
    """The part of a page's measure that breaks the rule; empty when the page meets it."""
    out = {k: v for k, v in m.items() if k != "words" and v}
    if m["words"] > PAGE and long_page_reason(name) is None:
        out["words"] = m["words"]
    return out


def load_baseline() -> dict[str, dict[str, int]]:
    return json.loads(BASELINE.read_text(encoding="utf-8"))


def current_debt() -> dict[str, dict[str, int]]:
    out = {}
    for page in pages():
        d = debt(rel(page), measure(page))
        if d:
            out[rel(page)] = d
    return out


def test_no_page_breaks_the_rule_beyond_its_baseline():
    baseline = load_baseline()
    failures = []
    for page in pages():
        name = rel(page)
        m = measure(page)
        allowed = baseline.get(name, {})
        cap = max(PAGE, allowed.get("words", 0))
        if long_page_reason(name) is None and m["words"] > cap:
            grew = "got longer" if name in baseline else "is over 700 words"
            failures.append(f"{name}: {m['words']} words (limit {cap}); it {grew}: split it")
        for key, label in (
            ("long_paragraphs", "paragraphs over 60 words"),
            ("long_sentences", "sentences over 25 words"),
        ):
            if m[key] > allowed.get(key, 0):
                failures.append(f"{name}: {m[key]} {label}, {allowed.get(key, 0)} allowed")
    assert not failures, "\n" + "\n".join(failures)


def test_the_baseline_follows_every_improvement():
    baseline, now = load_baseline(), current_debt()
    stale = sorted(
        name
        for name in set(baseline) | set(now)
        if any(now.get(name, {}).get(k, 0) < v for k, v in baseline.get(name, {}).items())
    )
    assert not stale, f"pages improved; lower their baseline: python {__file__} --update\n" + (
        "\n".join(stale)
    )


def test_every_long_page_has_a_reason():
    for key, reason in LONG_PAGES.items():
        assert reason.strip(), key
        hits = [p for p in pages() if long_page_reason(rel(p)) == reason]
        assert hits, f"{key} matches no page; remove it from LONG_PAGES"
        if not key.endswith("/"):
            assert measure(ROOT / key)["words"] > PAGE, (
                f"{key} is short now; remove it from LONG_PAGES"
            )


def report() -> None:
    baseline = load_baseline()
    for page in pages():
        name, m = rel(page), measure(page)
        flag = "" if not debt(name, m) else "  (baseline)" if name in baseline else "  NEW DEBT"
        print(
            f"{name:60} words={m['words']:5} long_paragraphs={m['long_paragraphs']:3} "
            f"long_sentences={m['long_sentences']:3}{flag}"
        )


if __name__ == "__main__":
    if "--update" in sys.argv[1:]:
        BASELINE.write_text(json.dumps(current_debt(), indent=2, sort_keys=True) + "\n")
        print(f"wrote {BASELINE}")
    else:
        report()
